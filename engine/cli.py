import argparse
import json
from collections import Counter, defaultdict
from datetime import datetime, timezone
from pathlib import Path
from engine.checks import academic_checks
from engine.content import apply_patches, digest, payload, title
from engine.models import Proposal, Result, Solve
from engine.provider import Gemini
from engine.reviewed import decisions
from engine.validation import validate_proposal
from engine.batching import generate_batch

ROOT = Path(__file__).resolve().parents[1]


def read(path):
    return json.loads((ROOT / path).read_text(encoding="utf-8"))


def write(path, value):
    dest = ROOT / path
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def generate_types(schema):
    def ts(s):
        if "$ref" in s:
            return s["$ref"].split("/")[-1]
        if "anyOf" in s:
            return " | ".join(ts(x) for x in s["anyOf"])
        if "enum" in s:
            return " | ".join(json.dumps(x) for x in s["enum"])
        if s.get("type") == "object":
            return "{ " + "; ".join(json.dumps(k) + ("" if k in s.get("required", []) else "?") + ": " + ts(v) for k, v in s.get("properties", {}).items()) + " }"
        if s.get("type") == "array":
            return "(" + ts(s["items"]) + ")[]"
        return {"string": "string", "number": "number", "integer": "number", "null": "null", "boolean": "boolean"}.get(s.get("type"), "unknown")
    lines = ["// Generated by engine.cli from Pydantic JSON Schema. Do not edit."]
    lines.extend("export type " + k + " = " + ts(v) + ";" for k, v in schema.get("$defs", {}).items())
    lines.append("export type Result = " + ts(schema) + ";")
    dest = ROOT / "apps/console/generated/contracts.ts"
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")


def load_data():
    questions, reports, taxonomy = [read("data/" + name + ".json") for name in ("questions", "reports", "taxonomy")]
    if len({q["_id"] for q in questions}) != len(questions) or len({r["reportId"] for r in reports}) != len(reports):
        raise ValueError("Duplicate source IDs")
    if set(r["questionId"] for r in reports) - set(q["_id"] for q in questions):
        raise ValueError("Unresolved question reference")
    return questions, reports, taxonomy


def validate_export(results, questions, reports, taxonomy):
    expected = {r["reportId"]: r["questionId"] for r in reports}
    if len(results) != len(reports) or {r["reportId"]: r["questionId"] for r in results} != expected:
        raise ValueError("Results must cover every source report exactly once")
    by_id = {q["_id"]: q for q in questions}
    for row in results:
        Result.model_validate(row)
        if row["verdict"] != "defect" and (row["repair"] is not None or row["edit"] is not None):
            raise ValueError("Non-defect results must not carry repairs or edits")
        rule = taxonomy["repairs"].get(row["repair"])
        if row["verdict"] == "defect" and not rule:
            raise ValueError("Unknown repair")
        if row["route"] == "auto_apply" and (not rule or not rule["auto"] or not row["edit"]):
            raise ValueError("Unsafe automatic route")
        if row["route"] == "no_change" and row["verdict"] == "defect":
            raise ValueError("A defect requires an apply or review route")
        if row["edit"]:
            errors = validate_proposal(by_id[row["questionId"]], row["verdict"], row["repair"], [row["edit"]], taxonomy)
            if errors:
                raise ValueError(str(errors))


def run(mode="reviewed", limit=None, max_calls=20, min_interval=20, candidate=False, batch_size=8):
    questions, reports, taxonomy = load_data()
    hashes = {name: digest(read("data/" + name + ".json")) for name in ("questions", "reports", "taxonomy")}
    if mode == "reviewed" and hashes != read("engine/source-lock.json"):
        raise ValueError("Reviewed catalog is bound to a different dataset; use live mode or explicitly re-review")
    by_id = {q["_id"]: q for q in questions}
    groups = defaultdict(list)
    for report in reports:
        groups[report["questionId"]].append(report)
    reviewed = decisions(questions) if mode == "reviewed" else None
    checks = academic_checks()
    if not all(c["passed"] for c in checks.values()):
        raise ValueError("An academic calculation check failed")
    provider = Gemini(ROOT / "artifacts/private-runs/gemini-cache", max_calls, min_interval) if mode == "live" else None
    results, cases = [], []
    interruption = None
    prepared = {}
    group_ids = list(groups)
    for index, (qid, group) in enumerate(groups.items()):
        if limit and index >= limit:
            break
        q = by_id[qid]
        solves = []
        if provider:
            try:
                if batch_size > 1:
                    if qid not in prepared:
                        stop = min(index + batch_size, limit or len(group_ids))
                        batch = [by_id[key] for key in group_ids[index:stop]]
                        print(f"Preparing batch of {len(batch)} grouped questions", flush=True)
                        prepared.update(generate_batch(provider, batch, groups, taxonomy))
                    proposal, solves = prepared[qid]
                else:
                    blind = {"questionType": q["questionType"], "question": payload(q)["question"], "quesImages": payload(q)["quesImages"]}
                    solves = [provider.generate(prompt, blind, Solve).model_dump() for prompt in ("solve-v1.txt", "verify-v1.txt")]
                    proposal = provider.generate("adjudicate-v1.txt", {"question": q,
                        "reports": [{k: r[k] for k in ("reportId", "reportedAt", "source", "comment")} for r in group],
                        "taxonomy": taxonomy, "blind_solves": solves}, Proposal).model_dump()
                proposal.update(checks=[], review=proposal.pop("unresolved"))
            except (RuntimeError, ValueError, OSError) as error:
                interruption = {"questionId": qid, "reason": str(error)}
                break
        else:
            proposal = reviewed[group[0]["reportId"]]
        patches = proposal["patches"]
        errors = validate_proposal(q, proposal["verdict"], proposal["repair"], patches, taxonomy)
        support = [checks[key] for key in proposal["checks"]]
        agree = bool(solves and solves[0]["answer"] is not None and solves[0]["answer"] == solves[1]["answer"] and all(s["sufficient_data"] and not s["assumptions"] for s in solves))
        rule = taxonomy["repairs"].get(proposal["repair"])
        low_risk = proposal["repair"] in ("spelling", "noise", "exam_reference", "markup_leak", "answer_form")
        # A live semantic edit requires blind agreement AND a faculty review.
        # Future promotion requires a deterministic verifier for that proposal.
        can_auto = bool(rule and rule["auto"] and patches and not errors and not proposal["review"] and
            (low_risk or (mode == "reviewed" and support)))
        route = "auto_apply" if can_auto else "faculty_review" if proposal["verdict"] == "defect" or proposal["review"] else "no_change"
        if errors:
            patches = []
            route = "faculty_review"
        # A documented ordinal evidence score, not a calibrated probability.
        score = .9 if support or agree else .8 if low_risk or proposal["verdict"] == "already_fixed" else .65
        if proposal["review"]:
            score = min(score, .75)
        if errors:
            score = .3
        evidence = proposal["evidence"] + ((" Validation blocked: " + "; ".join(errors)) if errors else "")
        for report in group:
            local = proposal if provider else reviewed[report["reportId"]]
            row = Result(reportId=report["reportId"], questionId=qid, verdict=proposal["verdict"],
                repair=proposal["repair"], edit=patches[0] if len(patches) == 1 else None, route=route,
                confidence=score, evidence=evidence, student_reply=local["student_reply"]).model_dump()
            results.append(row)
        severity = 3 if proposal["repair"] in ("answer_key", "unsound", "stem_data", "option_repair", "diagram", "type_mismatch") else 2 if proposal["verdict"] == "defect" else 1
        case = {"id": qid, "title": title(q), "question": q, "reports": group,
            "decision": {"verdict": proposal["verdict"], "repair": proposal["repair"], "route": route, "confidence": score, "evidence": evidence},
            "patches": patches, "sourceHash": digest(q), "checks": support, "blindSolves": solves,
            "validation": {"passed": not errors, "errors": errors, "scope": rule["fields"] if rule else []},
            "replies": {r["reportId"]: next(x["student_reply"] for x in results if x["reportId"] == r["reportId"]) for r in group},
            "priority": severity, "urgencyReason": "Answerability or scoring risk" if severity == 3 else "Content clarity" if severity == 2 else "Support or explanation",
            "oldestReport": min(r["reportedAt"] for r in group)}
        cases.append(case)
        print(f"{index + 1}/{len(groups)} {group[0]['reportId']} {route}", flush=True)
    results.sort(key=lambda r: r["reportId"])
    cases.sort(key=lambda c: (-c["priority"], -len(c["reports"]), c["oldestReport"]))
    full = len(results) == len(reports)
    if full:
        validate_export(results, questions, reports, taxonomy)
    manifest = {"schemaVersion": "1.0", "mode": mode, "generatedAt": datetime.now(timezone.utc).isoformat(),
        "inputHashes": hashes, "reportCount": len(results), "questionCount": len(cases), "complete": full,
        "model": provider.model if provider else None, "apiCallsThisRun": provider.calls if provider else 0,
        "cacheHits": provider.cache_hits if provider else 0,
        "thinkingLevel": provider.thinking_level or "model-default" if provider else None,
        "requestBudget": provider.max_calls if provider else None, "interruption": interruption,
        "batchSize": batch_size if provider else None,
        "confidenceMeaning": "Uncalibrated evidence rating: 0.90 calculation or blind agreement; 0.80 textual/history support; 0.65 limited support; unresolved capped at 0.75; blocked 0.30. Not a probability.",
        "promptHashes": {p.name: digest(p.read_text(encoding="utf-8")) for p in (ROOT / "engine/prompts").glob("*.txt")},
        "resultsHash": digest(results), "routeCounts": dict(Counter(r["route"] for r in results)),
        "disclosure": "Assistant-reviewed fixed-dataset baseline; no Gemini calls were made." if not provider else "Gemini-generated proposals; writes remain gated by deterministic policy."}
    if candidate:
        write("artifacts/live/results.json", results)
        write("artifacts/live/cases.json", cases)
        write("artifacts/live/manifest.json", manifest)
    elif full:
        write("results.json", results)
        write("artifacts/cases.json", cases)
        write("artifacts/manifest.json", manifest)
        write("artifacts/checks.json", list(checks.values()))
        write("contracts/result.schema.json", Result.model_json_schema())
        write("apps/console/generated/bundle.json", {"cases": cases, "manifest": manifest, "taxonomy": taxonomy, "results": results})
        generate_types(Result.model_json_schema())
    else:
        write("artifacts/private-runs/partial.json", {"results": results, "cases": cases, "manifest": manifest})
    print(json.dumps({"reports": len(results), "cases": len(cases), "complete": full, "mode": mode, "interruption": interruption}))
    return not interruption


def promote_live():
    results, cases, manifest = [read("artifacts/live/" + name + ".json") for name in ("results", "cases", "manifest")]
    questions, reports, taxonomy = load_data()
    if not manifest["complete"] or manifest["mode"] != "live" or manifest["resultsHash"] != digest(results):
        raise ValueError("Only a complete, intact live run may be promoted")
    for name, expected in manifest["inputHashes"].items():
        if digest(read("data/" + name + ".json")) != expected:
            raise ValueError("The input data changed since the live run")
    validate_export(results, questions, reports, taxonomy)
    write("results.json", results)
    write("artifacts/cases.json", cases)
    write("artifacts/manifest.json", manifest)
    write("apps/console/generated/bundle.json", {"cases": cases, "manifest": manifest, "taxonomy": taxonomy, "results": results})
    write("contracts/result.schema.json", Result.model_json_schema())
    generate_types(Result.model_json_schema())
    print("Promoted the complete live artifact to results.json and console bundle.")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mode", choices=["reviewed", "live"], default="reviewed")
    parser.add_argument("--limit", type=int)
    parser.add_argument("--validate-only", action="store_true")
    parser.add_argument("--max-api-calls", type=int, default=20)
    parser.add_argument("--min-request-interval", type=float, default=20)
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--candidate", action="store_true", help="Save a reviewable candidate without replacing the main artifact")
    parser.add_argument("--promote-live", action="store_true")
    args = parser.parse_args()
    if args.max_api_calls < 0 or args.min_request_interval < 0 or args.batch_size < 1 or args.limit is not None and args.limit < 1:
        parser.error("Request limits must be nonnegative and question limit must be positive")
    if args.promote_live:
        promote_live()
    elif args.validate_only:
        q, r, t = load_data()
        validate_export(read("results.json"), q, r, t)
        print("All source reports covered; result schema and export policies passed.")
    else:
        if not run(args.mode, args.limit, args.max_api_calls, args.min_request_interval, args.candidate, args.batch_size):
            raise SystemExit(2)


if __name__ == "__main__":
    main()
